"""Номер для новой записи, которую диспетчер добавил без номера.

Раньше автонумерацию сдвигали за самый большой существующий номер. После загрузки реальных
выгрузок, где номера девятизначные, новая заявка получала номер вроде 900000013 — читать и
диктовать такое невозможно. Поэтому берётся наименьший свободный номер.

Номера удалённых записей освобождаются, но удалить заявку или исполнителя, попавших в план
или событие, нельзя — «повторный» номер ни на что не сошлётся.
"""


def smallest_free_id(taken_ids: set[int]) -> int:
    """Наименьший положительный номер, которого ещё нет среди taken_ids."""
    candidate = 1
    while candidate in taken_ids:
        candidate += 1
    return candidate
