// Чем посчитан маршрут или пробег. Valhalla (по дорогам) и R5 (по расписанию общественного
// транспорта) — настоящий расчёт. Оценка — только когда маршрутизатор не ответил: haversine
// (по прямой) или transit_estimate (модель ОТ без R5). Раньше «не Valhalla» считалось оценкой,
// и честные маршруты на общественном транспорте ложно помечались «оценка по прямой».

const ESTIMATES = {
  haversine: 'оценка по прямой',
  transit_estimate: 'оценка без расписания',
}

const TITLES = {
  valhalla: 'Рассчитано по дорогам через Valhalla',
  r5: 'Рассчитано по расписанию общественного транспорта через R5',
  routed: 'Рассчитано по дорогам (Valhalla) и расписанию общественного транспорта (R5)',
  haversine: 'Оценка по прямой: маршрутизатор Valhalla был недоступен',
  transit_estimate: 'Оценка без расписания: R5 был недоступен, время по модели общественного транспорта',
  mixed: 'Часть маршрутов посчитана приближённо: маршрутизатор был недоступен',
}

// посчитано приближённо — рядом с числом ставим «≈» или «*»
export function isApproximate(provider) {
  return provider in ESTIMATES || provider === 'mixed'
}

// короткая пометка у маршрута: «оценка по прямой»; у настоящего расчёта — пусто
export function estimateNote(provider) {
  return ESTIMATES[provider] ?? ''
}

// подсказка при наведении: чем посчитано
export function providerTitle(provider) {
  return TITLES[provider] ?? ''
}
