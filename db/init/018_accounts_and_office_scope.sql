-- Учётки диспетчеров и разделение данных по офисам.
--
-- Офис обслуживает свой регион, и диспетчер работает только с ним: заявки, бригады и планы
-- чужих офисов ему не видны. Офис не выбирается в интерфейсе, как день, — он приходит из
-- учётки: диспетчер привязан к офису, администратор выбирает офис сам.
--
-- app_user — учётки. role: admin (справочники, пользователи, любой офис) или dispatcher
-- (только свой офис). Пароль — хэш scrypt (backend/src/core/security.py). Первый
-- администратор: логин admin, пароль admin — смените его после первого входа.
--
-- Разделение по офисам:
--   request.office_id  — чья заявка. Новая получает офис того, кто её завёл или загрузил.
--   engineer.office_id — чья бригада (раньше поле значило «откуда выезжает»). Откуда
--                        выезжает, теперь говорит start_at_office: из своего офиса или из
--                        своей точки start_latitude/start_longitude.
--   plan.office_id     — чей план. Утверждается один план на офис и день, а не на день.
--
-- Существующие данные раскладываются по офисам по ближайшей точке: заявка — по адресу,
-- бригада — по старту, план — по офису большинства своих бригад. Всё можно поправить руками.
BEGIN;

CREATE TABLE IF NOT EXISTS app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login         TEXT NOT NULL UNIQUE,
    name          TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role          TEXT NOT NULL CHECK (role IN ('admin', 'dispatcher')),
    office_id     BIGINT REFERENCES office (id),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    -- диспетчер без офиса не видел бы ничего
    CHECK (role = 'admin' OR office_id IS NOT NULL)
);
COMMENT ON TABLE app_user IS 'Учётки: администраторы и диспетчеры офисов';

