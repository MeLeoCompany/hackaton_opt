-- 049: черновик расчёта дня тоже считается на момент «сейчас плюс запас» (docs/algoV2.md, шаг 1).
--
-- Расчёт идёт не «прямо сейчас»: пока считаем и обзваниваем клиентов, время уходит, поэтому
-- бригады в задаче свободны не раньше T = момент расчёта + запас. С этого момента план и
-- начинает действовать — а после него утверждать уже нечего: маршруты начинались бы в прошлом.
-- Если к этому моменту появились новые вводные (заявка, отмена), утверждение тоже не проходит:
-- день считают заново. У черновика будущего дня момента нет — там торопиться некуда.

ALTER TABLE plan ADD COLUMN IF NOT EXISTS effective_at TIMESTAMPTZ;

COMMENT ON COLUMN plan.effective_at IS 'Черновик идущего дня: момент выезда, на который он посчитан (T+запас). После него черновик не утверждают';
