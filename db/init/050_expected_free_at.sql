-- 050: «освободится в HH:MM» со слов бригады живёт на заявке, а не только внутри пересчёта.
--
-- Оператор звонит застрявшей бригаде один раз и называет время. Раньше оно уходило в расчёт
-- и там же терялось: следующий пересчёт спрашивал снова и сам подставлял оценку с запасом,
-- отодвигая выезд всё дальше. Теперь время помнится до конца работы на этой заявке
-- (docs/algoV2.md, шаг 10).

ALTER TABLE request_fact ADD COLUMN IF NOT EXISTS expected_free_at TIMESTAMPTZ;

COMMENT ON COLUMN request_fact.expected_free_at IS 'Когда бригада закончит эту заявку — со слов оператора; спрашивается один раз';
