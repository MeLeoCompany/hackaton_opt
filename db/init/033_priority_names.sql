-- Уровни приоритета называются по степени важности, а не по видам работ.
--
--   1 Аварийный — важнее всего (аварии);
--   2 Высокий   — дальше (подключения);
--   3 Обычный   — остальное (ремонт, дозаказ).
-- Какой уровень подставляется заявке по умолчанию, задаёт соответствие «тип работ -> уровень»
-- (work_type.priority_id, справочник «Приоритеты»); в заявке его можно сменить.
BEGIN;

-- названия уникальны: сначала временные, чтобы название могло перейти к другому уровню
UPDATE priority SET name = name || ' (переименование)' WHERE id IN (1, 2, 3);
UPDATE priority SET name = 'Аварийный' WHERE level = 1;
UPDATE priority SET name = 'Высокий' WHERE level = 2;
UPDATE priority SET name = 'Обычный' WHERE level = 3;

COMMIT;
