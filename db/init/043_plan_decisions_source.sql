-- Черновик, пересчитанный после решений оператора при утверждении (docs/algoV2.md, шаги 2-5).
--
-- Первый расчёт дня может не взять часть заявок. Перед утверждением оператор обзванивает
-- этих клиентов: согласовать другое время, перенести на другой день, отменить. Решения
-- меняют заявки, и день считается заново — получается новый черновик, который оператор
-- смотрит и утверждает сам. Здесь запоминается, из какого черновика пришли решения и сколько
-- их было: в списке планов видно «учтены решения по N заявкам из №…».
BEGIN;

ALTER TABLE plan
    ADD COLUMN IF NOT EXISTS decisions_from_plan_id bigint REFERENCES plan (id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS decisions_count integer;

COMMENT ON COLUMN plan.decisions_from_plan_id IS 'Черновик, по невлезшим заявкам которого оператор принял решения перед этим расчётом';
COMMENT ON COLUMN plan.decisions_count IS 'Сколько решений по заявкам учтено в этом расчёте';

COMMIT;
