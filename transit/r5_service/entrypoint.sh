#!/bin/sh
# Запуск сервиса маршрутов.
#
# Поиск одного маршрута у R5 однопоточный, и заметная часть работы (сборка подробного
# ответа) идёт на стороне Python, где мешает GIL: потоки внутри одного процесса ускорения
# не дают. Поэтому параллелизм делается процессами — каждый со своей копией транспортной
# сети. Проверено на замере: две поездки подряд 9.8 с, две одновременно в два процесса 5.3 с.
#
# Копия сети стоит памяти, и r5py по умолчанию отдаёт JVM 80% всей памяти машины — на
# каждый процесс. Поэтому кучу задаём явно: R5_WORKERS × R5_MAX_MEMORY должно с запасом
# помещаться в память сервера.
set -e

printf 'max-memory: %s\n' "${R5_MAX_MEMORY:-80%}" > /etc/r5py.yml

exec python3 -m uvicorn app.main:app \
    --host 0.0.0.0 --port 8003 \
    --workers "${R5_WORKERS:-1}"
